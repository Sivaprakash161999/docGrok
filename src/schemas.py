"""
Pydantic schemas and typed contracts for the Document Assistant.
Defines data structures for user intent, specialist agent responses,
memory management, and the LangGraph conversation state.
"""

from __future__ import annotations

import operator
from datetime import datetime
from typing import Annotated, Any, Dict, List, Literal, Optional, Union
from langchain_core.messages import AnyMessage
from pydantic import BaseModel, Field


# ============================================================================
# 1. Intent Classification Schema
# ============================================================================

class UserIntent(BaseModel):
    """
    Structured classification of the user's intent.
    Used by the intent classification node to dynamically route execution.
    """
    intent_type: Literal["qa", "summarization", "calculation", "unknown"] = Field(
        ...,
        description="The primary intent category: 'qa' for factual questions, "
                    "'summarization' for synthesis/executive summaries, "
                    "'calculation' for arithmetic or quantitative evaluation, "
                    "or 'unknown' if outside these categories."
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score for the classification between 0.0 and 1.0."
    )
    reasoning: str = Field(
        ...,
        description="Concise rationale explaining why this intent was selected based on user input and history."
    )


# ============================================================================
# 2. Specialist Agent Response Schemas
# ============================================================================

class AnswerResponse(BaseModel):
    """
    Structured response generated by the Q&A Agent.
    Enforces precise answers with explicit document citations and confidence scoring.
    """
    question: str = Field(
        ...,
        description="The specific user question being addressed."
    )
    answer: str = Field(
        ...,
        description="Synthesized, factual answer derived directly from referenced documents. If information was not found in the documents, explicitly state that."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="Unique identifiers (doc_id) of documents used to formulate the answer."
    )
    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence level in the accuracy and completeness of the answer (0.0 to 1.0). Set to 0.0 if not found."
    )
    found: bool = Field(
        default=True,
        description="True if the required information was found in the document(s); False if absent or not found."
    )
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="UTC timestamp when this response was generated."
    )


class SummaryResponse(BaseModel):
    """
    Structured response generated by the Summarization Agent.
    Provides executive overviews and extracted key takeaways.
    """
    title: str = Field(
        ...,
        description="Concise descriptive title or topic for the summary."
    )
    summary: str = Field(
        ...,
        description="Comprehensive narrative summary synthesizing the key aspects of the document(s)."
    )
    key_points: List[str] = Field(
        default_factory=list,
        description="Salient bullet points highlighting critical findings, metrics, or takeaways."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="List of document identifiers (doc_id) summarized in this report."
    )
    found: bool = Field(
        default=True,
        description="True if the document was found and summarized; False if document or information was absent."
    )
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="UTC timestamp when this summary was produced."
    )


class CalculationResponse(BaseModel):
    """
    Structured response generated by the Calculation Agent.
    Tracks numerical reasoning, deterministic formula execution, and citations.
    """
    operation_description: str = Field(
        ...,
        description="Plain-text explanation of the mathematical problem or metric being calculated."
    )
    expression: str = Field(
        ...,
        description="The exact arithmetic expression evaluated by the calculator tool (e.g. '1250000 * 0.18'). If missing, set to 'N/A'."
    )
    result: float = Field(
        default=0.0,
        description="The evaluated numeric result returned by the calculator."
    )
    formatted_result: str = Field(
        ...,
        description="Human-readable representation with appropriate formatting (e.g. '$225,000.00' or 'N/A')."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="Document identifiers from which the raw numerical values were extracted."
    )
    explanation: str = Field(
        ...,
        description="Contextual explanation of how this calculated metric answers the user's inquiry, or explanation that data is missing."
    )
    found: bool = Field(
        default=True,
        description="True if all required numbers were found and calculated; False if essential numbers were absent."
    )
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="UTC timestamp of the calculation."
    )


# ============================================================================
# 3. Context & Memory Update Schema
# ============================================================================

class MemoryUpdate(BaseModel):
    """
    Structured update produced by the update_memory node to persist rolling context.
    """
    conversation_summary: str = Field(
        ...,
        description="Condensed, progressive summary of the multi-turn conversation so far."
    )
    active_documents: List[str] = Field(
        default_factory=list,
        description="Cumulative list of document IDs relevant to the current conversation context."
    )


# ============================================================================
# 4. LangGraph Agent State Definition
# ============================================================================

from typing_extensions import TypedDict

class AgentState(TypedDict, total=False):
    """
    State dictionary flowing through the LangGraph workflow.
    Uses operator.add reducer for actions_taken to maintain execution lineage.
    """
    # Current input and chat messages
    user_input: str
    messages: List[AnyMessage]

    # Explicit / passed target documents (supports single, multiple, or hybrid external+corpus)
    target_document: Optional[Union[Dict[str, Any], List[Dict[str, Any]]]]
    target_doc_id: Optional[Union[str, List[str]]]
    target_documents: Optional[List[Dict[str, Any]]]
    target_doc_ids: Optional[List[str]]
    persist_target_document: bool

    # Classification & Routing
    intent: Optional[UserIntent]
    next_step: Optional[str]

    # Persistent Memory & Context
    conversation_summary: Optional[str]
    active_documents: List[str]

    # Working Responses & Tool Invocations
    current_response: Optional[Union[AnswerResponse, SummaryResponse, CalculationResponse, Dict[str, Any], str]]
    tools_used: List[str]

    # Session & User metadata
    session_id: str
    user_id: str

    # Execution lineage with operator.add reducer
    actions_taken: Annotated[List[str], operator.add]
